export const formatRobotControlText = (language, text, values = []) => {
  const translated = language === 'VI' ? (vietnamese[text] || text) : text;
  return translated.replace(/\{(\d+)\}/g, (match, index) => values[index] ?? match);
};

export const useRobotControlText = () => {
  const { language } = useLanguage();
  const languageRef = useRef(language);
  languageRef.current = language;
  // Keep existing subscriptions and control handlers stable when language changes.
  return useCallback((text, values) => formatRobotControlText(languageRef.current, text, values), []);
};
